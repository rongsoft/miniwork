func (m *Mock) Fetch(ctx context.Context, q Query) ([]Hotspot, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if kw := strings.TrimSpace(q.Keyword); kw != "" {
		return m.search(ctx, kw, q.Niche)
	}
	return m.fetchNiche(ctx, q.Niche)
}

// search 按关键词跨赛道找内容。
//
// 语料里的 [词] 标记本身就是现成的关键词索引：它标的是「这条在讲什么」，
// 而不是「这条属于哪个赛道」。所以先比标记、再比标题子串——
// 「部门要裁员时，第一批走的是哪种人」标题里有「裁员」，
// 但「被优化那天，我才明白公司从来不是家」标题里没有，标记里有 [优化]。
// 只比标题会漏掉一大批同义表达。
//
// 搜不到就是搜不到，不造数据。示例语料只覆盖 8 个赛道，
// 用户搜「宠物」拿到一条编的「宠物经济爆发」，比拿到空结果更糟——
// 他会以为数据源真的有这个能力，然后信任一份假素材。
func (m *Mock) search(ctx context.Context, keyword, niche string) ([]Hotspot, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}

	now := time.Now()
	out := make([]Hotspot, 0, 16)
	weight := map[string]int{}
	seen := map[string]bool{}

	for n, list := range nicheCorpus {
		for _, raw := range list {
			w := 0
			for _, mk := range marks(raw) {
				if matchKeyword(mk, keyword) {
					w = 3 // 标记命中：这条确实在讲这个
					break
				}
			}
			if w == 0 && strings.Contains(stripMark(raw), keyword) {
				w = 1 // 只是标题里出现了字面
			}
			if w == 0 {
				continue
			}
			title := stripMark(raw)
			if seen[title] {
				continue
			}
			seen[title] = true
			weight[title] = w
			out = append(out, m.hotspotFor(title, n, now))
		}
	}

	// 先按命中强度，再按热度。同一关键词反复搜，结果顺序必须稳定，
	// 否则用户会以为数据在乱跳。
	sort.SliceStable(out, func(i, j int) bool {
		if weight[out[i].Title] != weight[out[j].Title] {
			return weight[out[i].Title] > weight[out[j].Title]
		}
		return out[i].Heat > out[j].Heat
	})
	return out, nil
}

// hotspotFor 用标题派生一个稳定的热度与时间。
//
// 不能用随机数：同一个关键词两次搜索，如果热度从 8 万变成 2 万，
// 用户会以为在拿假数据糊弄他。用标题哈希派生，同一条内容永远同一组数据。
func (m *Mock) hotspotFor(title, niche string, now time.Time) Hotspot {
	sum := sha256.Sum256([]byte("mock|" + title))
	a := binary.BigEndian.Uint32(sum[0:4])
	b := binary.BigEndian.Uint32(sum[4:8])

	heat := int64(math.Pow(10, 3+float64(a%1000)/1000*3))
	hours := float64(b%6000) / 100 // 0-60 小时
	published := now.Add(-time.Duration(hours * float64(time.Hour)))

	platform := "xiaohongshu"
	if a%3 == 0 {
		platform = "douyin"
	}
	return Hotspot{
		ID:          contentID(platform, title),
		Platform:    platform,
		Title:       title,
		Author:      fmt.Sprintf("作者%02d", a%50),
		URL:         fmt.Sprintf("https://example.com/kw/%s", contentID(platform, title)),
		Heat:        heat,
		Tags:        []string{niche},
		PublishedAt: published,
		FetchedAt:   now,
	}
}

// marks 取出语料里的 [关键词] 标记。
func marks(raw string) []string {
	var out []string
	for {
		i := strings.IndexByte(raw, '[')
		if i < 0 {
			return out
		}
		j := strings.IndexByte(raw[i:], ']')
		if j < 0 {
			return out
		}
		out = append(out, raw[i+1:i+j])
		raw = raw[i+j+1:]
	}
}

// matchKeyword 双向包含：
// 「裁员」要能命中标记「裁员」，也要能命中用户输入的「裁员赔偿」。
func matchKeyword(mark, keyword string) bool {
	return mark == keyword || strings.Contains(mark, keyword) || strings.Contains(keyword, mark)
}

// fetchNiche 是按赛道常规抓取，也就是关键词为空时的路径。
func (m *Mock) fetchNiche(ctx context.Context, niche string) ([]Hotspot, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}

	count := m.Count
	if count <= 0 {
		count = 40
	}
	noise := m.Noise
	if noise <= 0 {
		noise = 0.3
	}

	corpus, ok := nicheCorpus[niche]
	if !ok {
		return nil, fmt.Errorf("mock 不支持的赛道: %q", niche)
	}

	// 每一轮换一个种子。
	//
	// 固定种子的话，同一个赛道每次抽出来的都是同一批标题，去重之后
	// 「刷新」等于什么都没做——用户点十次看到的还是那九条，会以为
	// 按钮坏了。Seed 仍然当基准，只是混进一个每轮都在变的值。
	round := m.Seed ^ uint64(time.Now().UnixNano())
	rnd := rand.New(rand.NewPCG(round, 0x9E3779B9))
	now := time.Now()
	out := make([]Hotspot, 0, count)

	// 每轮只抽语料的一半左右。
	//
	// 抽满的话，第一轮就把整个语料翻了个遍，之后无论种子怎么变
	// 都只剩「已收过」。留一半下来，连续刷新的前几次才真的能见到
	// 新东西——这是示例数据必须有的手感，否则演示不了「每天有新的」。
	pool := make([]string, len(corpus))
	copy(pool, corpus)
	rnd.Shuffle(len(pool), func(i, j int) { pool[i], pool[j] = pool[j], pool[i] })
	if half := len(pool)/2 + 2; half < len(pool) {
		pool = pool[:half]
	}

	for i := 0; i < count; i++ {
		var title string
		if rnd.Float64() < noise {
			title = noiseCorpus[rnd.IntN(len(noiseCorpus))]
		} else {
			title = pool[rnd.IntN(len(pool))]
		}

		// 热度用对数分布，贴近真实：少数爆款，长尾很多。
		heat := int64(math.Pow(10, 3+rnd.Float64()*3))

		// 时效 0-60 小时，偏向最近。
		hours := rnd.Float64() * rnd.Float64() * 60
		published := now.Add(-time.Duration(hours * float64(time.Hour)))

		platform := "xiaohongshu"
		if rnd.IntN(3) == 0 {
			platform = "douyin"
		}

		out = append(out, Hotspot{
			ID:          contentID(platform, title),
			Platform:    platform,
			Title:       stripMark(title),
			Author:      fmt.Sprintf("作者%02d", rnd.IntN(50)),
			URL:         fmt.Sprintf("https://example.com/%s/%d", platform, i),
			Heat:        heat,
			Tags:        []string{niche},
			PublishedAt: published,
			FetchedAt:   now,
		})
	}

	// 同标题只保留热度最高的一条，模拟真实去重后的结果。
	seen := map[string]int{}
	dedup := out[:0]
	for _, h := range out {
		if idx, ok := seen[h.Title]; ok {
			if h.Heat > dedup[idx].Heat {
				dedup[idx] = h
			}
			continue
		}
		seen[h.Title] = len(dedup)
		dedup = append(dedup, h)
	}
	return dedup, nil
}

// contentID 用平台+标题派生稳定 id。
// 不能用下标：下标一换，同一条内容就变成新记录，去重和幂等全部失效。
func contentID(platform, title string) string {
	sum := sha256.Sum256([]byte(platform + "|" + title))
	return hex.EncodeToString(sum[:8])
}

// stripMark 去掉语料里的 [] 标记，它们只用于给打分器做赛道提示。
func stripMark(s string) string {
	b := make([]byte, 0, len(s))
	for i := 0; i < len(s); i++ {
		if s[i] == '[' || s[i] == ']' {
			continue
		}
		b = append(b, s[i])
	}
	return string(b)
}
