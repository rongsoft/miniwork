// nicheOrder 是稳定输出顺序，8 个赛道和客户端 Niches() 保持一致。
var nicheOrder = []string{"职场", "副业", "理财", "育儿", "健身", "美食", "穿搭", "AI工具"}

// Hotspot 与数据接口约定里的 items 元素一一对应。
type Hotspot struct {
	ID          string   `json:"id"`
	Platform    string   `json:"platform"`
	Title       string   `json:"title"`
	Author      string   `json:"author"`
	URL         string   `json:"url"`
	Heat        int64    `json:"heat"`
	Tags        []string `json:"tags"`
	PublishedAt string   `json:"publishedAt"`
}

// stableID 用赛道+平台+标题派生 id：同一条内容永远同一个 id。
// 不能用下标——服务端重启、语料顺序变化都会让 id 漂移，客户端就会重复入库。
func stableID(niche, platform, title string) string {
	sum := sha256.Sum256([]byte(niche + "|" + platform + "|" + title))
	return "mw_" + hex.EncodeToString(sum[:8])
}

// hashUnit 把字符串稳定地映射到 [0,1)，用于派生热度、作者、发布时间。
func hashUnit(s string) float64 {
	sum := sha256.Sum256([]byte(s))
	v := uint64(0)
	for i := 0; i < 8; i++ {
		v = v<<8 | uint64(sum[i])
	}
	return float64(v%1000000) / 1000000
}

type snapshot struct {
	Stale       bool                 `json:"stale"`
	GeneratedAt string               `json:"generatedAt"`
	Items       map[string][]Hotspot `json:"-"`
}

// buildSnapshot 按当前时间生成一份快照。
//
// visible(niche) = base + floor(运行时长 / refreshInterval) * step，封顶语料总数。
// 随时间放量是为了让「刷新灵感」真的能刷出新东西；id 仍然稳定，
// 老条目只在被新条目顶出 limit 窗口时才从界面消失。
func buildSnapshot(cfg Config, started time.Time, now time.Time) snapshot {
	snap := snapshot{
		GeneratedAt: now.UTC().Format(time.RFC3339),
		Items:       make(map[string][]Hotspot, len(nicheOrder)),
	}
	elapsed := now.Sub(started)
	if elapsed < 0 {
		elapsed = 0
	}
	rounds := int(elapsed / cfg.RefreshInterval())
	visible := cfg.BaseItems + rounds*cfg.StepItems

	for _, niche := range nicheOrder {
		titles := corpus[niche]
		if visible < len(titles) {
			titles = titles[:visible]
		}
		items := make([]Hotspot, 0, len(titles))
		for i, title := range titles {
			platform := "xiaohongshu"
			if hashUnit(title+"#p") < 0.34 {
				platform = "douyin"
			}
			id := stableID(niche, platform, title)
			// 热度用对数分布：少数爆款，长尾很多。基于 id 稳定，不会每次刷新乱跳。
			heat := int64(1000 + 400000*hashUnit(id+"#h")*hashUnit(id+"#h"))
			if heat < 1000 {
				heat = 1000
			}
			// 发布时间落在最近 12 小时内，基于 id 稳定。
			age := time.Duration(hashUnit(id+"#t") * 12 * float64(time.Hour))
			pub := now.Add(-age)
			// URL 用稳定的 id，方便排查「这条数据哪来的」。
			url := "https://www.xiaohongshu.com/explore/" + strings.TrimPrefix(id, "mw_")
			if platform == "douyin" {
				url = "https://www.douyin.com/video/" + strings.TrimPrefix(id, "mw_")
			}
			items = append(items, Hotspot{
				ID:          id,
				Platform:    platform,
				Title:       title,
				Author:      "hot_" + strings.TrimPrefix(id, "mw_")[:4],
				URL:         url,
				Heat:        heat,
				Tags:        []string{niche, "热点"},
				PublishedAt: pub.UTC().Format(time.RFC3339),
			})
			_ = i
		}
		// 新的排前面：客户端今天这批优先展示，用户能立刻看到刚露出的内容。
		sort.SliceStable(items, func(i, j int) bool {
			if items[i].PublishedAt != items[j].PublishedAt {
				return items[i].PublishedAt > items[j].PublishedAt
			}
			return items[i].Heat > items[j].Heat
		})
		snap.Items[niche] = items
	}
	return snap
}
